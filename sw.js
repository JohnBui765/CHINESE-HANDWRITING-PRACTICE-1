// PRECACHE-END
const CACHE = PREFIX + VERSION;

// Install: download every app file into this version's cache.
self.addEventListener('install', event => {
  event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(PRECACHE)));
});

// Activate: delete this app's OLD caches only. Other apps' caches are never touched.
self.addEventListener('activate', event => {
  event.waitUntil(
    caches.keys().then(names => Promise.all(
      names
        .filter(name => name.startsWith(PREFIX) && name !== CACHE)
        .map(name => caches.delete(name)),
    )),
  );
});

// Fetch: answer from this app's cache first, otherwise from the network.
self.addEventListener('fetch', event => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  const appFolder = new URL('./', self.location).pathname;
  if (url.origin !== self.location.origin || !url.pathname.startsWith(appFolder)) return;
  event.respondWith(
    caches.open(CACHE)
      .then(cache => cache.match(request, { ignoreSearch: true }))
      .then(hit => hit || fetch(request)),
  );
});
